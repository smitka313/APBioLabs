/* "Saved ✓" status line, and the "Pick up where you left off" card on the home page */
const T = require('./_h');
const OUT = process.env.OUT || require('os').tmpdir();
(async () => {
  const b = await T.launch(), ctx = await T.ctxFor(b);
  const p = await T.open(ctx, 'lab05.html', 'float-assay');
  const n = await p.evaluate(() => document.querySelectorAll('.save-status').length);
  const parts = await p.evaluate(() => document.querySelectorAll('section.step').length);
  T.ok(n >= parts, `a status line in every part and by Submit (${n} for ${parts} parts)`);
  const live = await p.evaluate(() => { const s = document.querySelector('section.step.is-current .save-status'); return !!(s.querySelector('[aria-live=polite]') && s.firstChild.getAttribute('aria-hidden') === 'true'); });
  T.ok(live, 'polite live region present, visible text aria-hidden');
  await p.goto('file://' + T.ROOT + '/lab05.html#analyze'); await p.waitForTimeout(600);
  const ta = p.locator('section.step.is-current textarea[data-save]').first();
  T.ok(await ta.count() > 0, 'found a prompt');
  await ta.fill('hello'); await p.waitForTimeout(900);
  let txt = await p.evaluate(() => document.querySelector('section.step.is-current .save-status').firstChild.textContent);
  T.ok(/^Saved ✓ just now$/.test(txt), 'after typing: ' + txt);
  const spoken = await p.evaluate(() => document.querySelector('section.step.is-current .save-status [aria-live]').textContent);
  T.ok(/saved/i.test(spoken), 'live region said: ' + spoken);
  await p.evaluate(() => { const real = Date.now; Date.now = () => real() + 130000; Lab.saveStatus.render(); });
  txt = await p.evaluate(() => document.querySelector('section.step.is-current .save-status').firstChild.textContent);
  T.ok(/^Saved ✓ 2 min ago$/.test(txt), 'after 2 min: ' + txt);
  await p.locator('section.step.is-current .save-status').scrollIntoViewIfNeeded();
  await p.screenshot({ path: OUT + '/saved-ok.png' });
  await p.evaluate(() => { Storage.prototype.setItem = function () { throw new Error('quota'); }; });
  await ta.fill('hello again'); await p.waitForTimeout(1200);
  txt = await p.evaluate(() => document.querySelector('section.step.is-current .save-status').firstChild.textContent);
  T.ok(txt === 'Not saved — see warning', 'storage failure: ' + txt);
  T.ok(await p.evaluate(() => !!document.querySelector('.storage-warn')), 'storage warning shown');
  await p.evaluate(() => window.scrollTo(0, 0));
  await p.screenshot({ path: OUT + '/saved-bad.png' });
  T.ok(p.errors.length === 0, 'no errors ' + p.errors.join('|'));
  await p.close();

  // ---- home ----
  const ctx2 = await T.ctxFor(b);
  let h = await T.open(ctx2, 'index.html');
  T.ok(await h.evaluate(() => document.getElementById('resume').hidden), 'new visitor: no pick-up card');
  await h.screenshot({ path: OUT + '/home-new.png' });
  await h.close();
  const lp = await T.open(ctx2, 'lab05.html', 'float-assay');
  await lp.waitForTimeout(1500);
  const hint = await lp.evaluate(() => { const e = document.querySelector('section.step.is-current .steps-next'); return e && e.textContent; });
  T.ok(!!hint, 'part has a Next hint: ' + hint);
  await lp.close();
  h = await T.open(ctx2, 'index.html');
  const card = await h.evaluate(() => { const e = document.getElementById('resume'); const a = e.querySelector('a.resume-link'); return { hidden: e.hidden, text: e.innerText, first: document.querySelector('.hero .wrap').firstElementChild === e, href: a && a.getAttribute('href') }; });
  console.log(card.text.replace(/\n+/g, ' | '));
  T.ok(!card.hidden && card.first, 'card visible and first in hero');
  T.ok(/Pick up where you left off/i.test(card.text) && /Lab 5/.test(card.text) && /Part:\s*Float assay/i.test(card.text), 'lab name and part');
  T.ok(/Next:/.test(card.text), 'Next hint shown');
  T.ok(/\d+ of \d+ parts done/.test(card.text), 'progress shown');
  T.ok(!/AP Bio Lab Bench/.test(card.text), 'title suffix stripped');
  T.ok(/lab05\.html#/.test(card.href), 'resume link ' + card.href);
  await h.screenshot({ path: OUT + '/home-returning.png' });
  T.ok(h.errors.length === 0, 'home no errors ' + h.errors.join('|'));
  await b.close();
  T.done('t17-saved-resume');
})();
