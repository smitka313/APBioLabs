module.exports = async ({ b, ok, ctxAs, open, keyres, ownText, frqChecks, frqReload }) => {
  const L = 'lab02';
  const start = p => p.evaluate(() => ['#card-n', '#ss-p', '#mg-p', '#cs-aa', '#cs-ab', '#cs-bb'].map(s => document.querySelector(s).value).join(','));
  const c1 = await ctxAs(b, 'Ada Lovelace', '3'), c2 = await ctxAs(b, 'Grace Hopper', '3');
  const p = await open(c1, 'lab02.html'), p2 = await open(c2, 'lab02.html');
  const a1 = await start(p), a2 = await start(p2);
  ok(a1 !== a2, 'two students get different starting values (' + a1 + ' vs ' + a2 + ')');
  await p.reload(); await p.waitForTimeout(900);
  ok((await start(p)) === a1, 'same student gets identical starting values after reload');
  await p2.close();
  await p.evaluate(() => Lab.pages.go('analyze')); await p.waitForTimeout(300);
  ok(/Finish Many generations/.test(await ownText(p, 'own-drift')), 'own-drift waits for data');
  ok(/Finish Build the model/.test(await ownText(p, 'own-spreadsheet')), 'own-spreadsheet waits for data');

  const predict = async () => { for (const k of ['predict-card', 'predict-spreadsheet', 'predict-drift', 'predict-design']) { await p.evaluate(k => { const t = document.getElementById('p-' + k); if (t) { t.value = 'I predict something because reasons here.'; t.dispatchEvent(new Event('input', { bubbles: true })); t.dispatchEvent(new Event('change', { bubbles: true })); } }, k); } };
  await predict();
  await p.evaluate(() => Lab.pages.go('build-the-model')); await p.waitForTimeout(300);
  await p.fill('#ss-n', '16'); await p.dispatchEvent('#ss-n', 'change');
  await p.click('#ss-record'); await p.waitForTimeout(200);
  await p.fill('#ss-n', '1000'); await p.dispatchEvent('#ss-n', 'change');
  await p.click('#ss-record'); await p.waitForTimeout(200);
  await p.evaluate(() => Lab.pages.go('many-generations')); await p.waitForTimeout(300);
  await p.click('#mg-run'); await p.waitForTimeout(1500);
  await p.click('#mg-record'); await p.waitForTimeout(400);
  await p.evaluate(() => Lab.pages.go('analyze')); await p.waitForTimeout(300);
  await p.fill('#cs-aa', '30'); await p.fill('#cs-ab', '40'); await p.fill('#cs-bb', '30'); await p.click('#cs-run'); await p.waitForTimeout(2000);
  const o1 = await ownText(p, 'own-drift'), o2 = await ownText(p, 'own-spreadsheet');
  ok(/SD = \d\.\d+, mean p = \d\.\d+/.test(o1), 'own-drift quotes real run: ' + o1.slice(0, 130));
  ok(/Δp = -?\d\.\d+ \(run \d: N = (16|1000)/.test(o2), 'own-spreadsheet quotes real run: ' + o2.slice(0, 130));
  const k1 = await keyres(p, L, 'mg-final-p'), k2 = await keyres(p, L, 'chi2-hw'), k3 = await keyres(p, L, 'ss-max-dp');
  ok(k1 && k1.value >= 0, 'mg-final-p stored ' + JSON.stringify(k1));
  ok(k2 && k2.value >= 0, 'chi2-hw stored ' + JSON.stringify(k2));
  ok(k3 && isFinite(k3.value), 'ss-max-dp stored ' + JSON.stringify(k3));
  ok(await keyres(p, L, 'mg-fixed-lost') !== null, 'mg-fixed-lost stored');
  await frqChecks(p, L);
  await p.reload(); await p.waitForTimeout(1200);
  await p.evaluate(() => Lab.pages.go('analyze')); await p.waitForTimeout(2000);
  ok(/SD = \d\.\d+/.test(await ownText(p, 'own-drift')), 'personal prompt quotes values after reload');
  ok((await keyres(p, L, 'chi2-hw')).value === k2.value, 'key results survive reload');
  await frqReload(p, L);
  await c1.close(); await c2.close();
};
