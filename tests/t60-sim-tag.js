/* Audit 5 #4: modeled vs observed data. Every Lab.chart with data and every Lab.table carries a small "Simulated data" tag;
   the .docx, the PDF view and the copied text say "All data in this report were generated by a computer simulation, not
   measured in a wet lab."; the first "observed" field or column on a lab page gets one short note (the word itself stays).
   Readable in light and dark (contrast >= 4.5:1).
   Run: NODE_PATH=$(npm root -g) node tests/t60-sim-tag.js */
const T = require('./_h');
const D = require('./t59-drive');
const path = require('path');
const SIM = 'All data in this report were generated by a computer simulation, not measured in a wet lab.';
const contrast = p => p.evaluate(() => {
  const rgb = c => (c.match(/[\d.]+/g) || []).slice(0, 3).map(Number);
  const lum = c => { const [r, g, b] = rgb(c).map(v => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; }); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
  const bgOf = e => { for (let a = e; a; a = a.parentElement) { const b = getComputedStyle(a).backgroundColor; if (b && !/rgba\(.*,\s*0\)$/.test(b) && b !== 'transparent') return b; } return 'rgb(255,255,255)'; };
  const ratio = e => { const f = lum(getComputedStyle(e).color), b = lum(bgOf(e)); return (Math.max(f, b) + 0.05) / (Math.min(f, b) + 0.05); };
  const out = {};
  const tag = document.querySelector('.sim-tag'); if (tag) out.tag = ratio(tag);
  const note = document.querySelector('.sim-note'); if (note) out.note = ratio(note);
  return out;
});
(async () => {
  const b = await T.launch();
  const ctx = await T.ctxFor(b);
  await ctx.addInitScript(() => { window.__copied = ''; try { Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async t => { window.__copied = t; } } }); } catch (e) { /* ignore */ } });

  // Every lab: each Lab.table has its tag; empty charts have none; "observed" note only where the word is used.
  const OBS = { lab02: 1, lab07: 1, lab12: 1 };
  for (const lab of T.LABS) {
    const p = await T.open(ctx, lab + '.html');
    const r = await p.evaluate(() => {
      const tables = Array.from(document.querySelectorAll('table.data')).filter(t => t.parentElement.matches('.table-wrap') && t.parentElement.parentElement && t.parentElement.parentElement.querySelector(':scope > .sim-tag'));
      const wraps = Array.from(document.querySelectorAll('.sim-tag')).filter(t => !(t.previousElementSibling && (t.previousElementSibling.matches('.table-wrap') || t.previousElementSibling.matches('.scroll-hint'))));
      const emptyTagged = Array.from(document.querySelectorAll('.chart.is-empty .sim-tag-svg')).length;
      return { tagged: tables.length, tags: document.querySelectorAll('.sim-tag').length, loose: wraps.length, emptyTagged, notes: document.querySelectorAll('.sim-note').length, noteText: (document.querySelector('.sim-note') || {}).textContent || '' };
    });
    T.ok(r.tags === r.tagged && r.loose === 0, `${lab}: ${r.tags} "Simulated data" tag(s), each right under its table`);
    T.ok(r.emptyTagged === 0, `${lab}: no tag on an empty chart`);
    T.ok(r.notes === (OBS[lab] || 0), `${lab}: ${r.notes} "observed" note(s) (expected ${OBS[lab] || 0})`);
    if (r.notes) T.ok(/“Observed” here means what you observed in the simulation/.test(r.noteText), `${lab}: note says observed = in the simulation`);
    T.ok(p.errors.length === 0, `${lab}: no page errors ` + p.errors.join(' | '));
    await p.close();
  }
  // The AP term stays on the labels.
  { const p = await T.open(ctx, 'lab12.html'); T.ok(/^Observed at end A/.test(await p.textContent('label[for=x-a]')), 'lab12: label still says "Observed at end A"'); await p.close(); }

  // A real run: the chart with data is tagged, in the page and in the report PNG's source SVG; the report header says so.
  const p = await T.open(ctx, 'lab05.html');
  await D.RUN.lab05(p);
  const ch = await p.evaluate(() => Array.from(document.querySelectorAll('.chart:not(.is-empty) > svg')).map(s => ({ tag: !!s.querySelector('.sim-tag-svg'), label: s.getAttribute('aria-label'), id: s.parentElement.id || s.parentElement.className })));
  T.ok(ch.length > 0 && ch.every(c => c.tag), `lab05: every chart with data is tagged (${ch.length}) ` + JSON.stringify(ch.filter(c => !c.tag)));
  T.ok(ch.every(c => /\(simulated data\)$/.test(c.label)), 'lab05: chart aria-label ends "(simulated data)"');
  await p.evaluate(() => Lab.pages && Lab.pages.showAll && Lab.pages.showAll(true)); await p.waitForTimeout(400);
  const overlap = await p.evaluate(() => Array.from(document.querySelectorAll('.chart:not(.is-empty) > svg')).filter(s => s.getBoundingClientRect().width).map(s => {
    const t = s.querySelector('.sim-tag-svg').getBoundingClientRect(), sr = s.getBoundingClientRect();
    const hit = Array.from(s.querySelectorAll('text:not(.sim-tag-svg)')).filter(x => { const r = x.getBoundingClientRect(); return r.width && r.left < t.right && r.right > t.left && r.top < t.bottom && r.bottom > t.top; }).map(x => x.textContent + '@' + JSON.stringify(x.getBoundingClientRect()) + ' tag ' + JSON.stringify(t));
    return { hit: hit.length ? hit : null, inside: t.left >= sr.left - 1 && t.right <= sr.right + 1 && t.top >= sr.top - 1 };
  }));
  T.ok(overlap.length > 0 && overlap.every(o => !o.hit && o.inside), 'lab05: the chart tag is inside the image and overlaps no other text ' + JSON.stringify(overlap.filter(o => o.hit || !o.inside)));
  await p.addScriptTag({ path: path.join(__dirname, 'fixtures/jszip-3.10.1.min.js') });
  const docXml = await p.evaluate(async () => { const blob = await Lab.report.docx({ timelapse: false }); const z = await JSZip.loadAsync(await blob.arrayBuffer()); return z.file('word/document.xml').async('string'); });
  T.ok(docXml.includes(SIM), '.docx header: "All data in this report were generated by a computer simulation…"');
  const head = await p.evaluate(async () => { await Lab.report.open(); const t = document.querySelector('#lab-report header').textContent; Lab.report.close(); return t; });
  T.ok(head.includes(SIM), 'PDF view header has the same line');
  await p.evaluate(() => Lab.pages && Lab.pages.showAll && Lab.pages.showAll(true));
  await p.click('button:has-text("Copy all my responses")'); await p.waitForTimeout(300);
  T.ok((await p.evaluate(() => window.__copied)).includes(SIM), 'copied text has the same line');
  T.ok(p.errors.length === 0, 'lab05 run: no page errors ' + p.errors.join(' | '));
  await ctx.close();

  // Readable in light and dark.
  for (const dark of [false, true]) {
    const c2 = await T.ctxFor(b, { dark });
    const q = await T.open(c2, 'lab12.html', 'analyze');
    const r = await contrast(q);
    T.ok(r.tag >= 4.5 && r.note >= 4.5, `${dark ? 'dark' : 'light'}: tag ${r.tag && r.tag.toFixed(2)}:1, note ${r.note && r.note.toFixed(2)}:1 (>= 4.5)`);
    await c2.close();
  }
  await b.close(); T.done('t60-sim-tag');
})();
