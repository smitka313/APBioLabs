/* Generates projector-data.js (used by projector.html) from the 13 lab pages: title, driving question, parts
   (slug, name, minutes, Lab.steps checklist text) and safety text. Pure regex extraction, no browser needed.
   Re-run after a lab's parts, steps or safety callout change:   node tools/gen-projector-data.js
   tests/t37-projector.js checks the output against the live pages. */
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
const slugify = s => String(s || '').normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/&/g, ' and ').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
const ent = { '&amp;': '&', '&lt;': '<', '&gt;': '>', '&quot;': '"', '&#39;': "'", '&nbsp;': ' ', '&deg;': '°', '&ndash;': '–', '&mdash;': '—', '&times;': '×', '&micro;': 'µ', '&plusmn;': '±', '&rarr;': '→', '&lambda;': 'λ', '&mu;': 'µ' };
const txt = h => h.replace(/<sub>([^<]*)<\/sub>/g, '$1').replace(/<sup>([^<]*)<\/sup>/g, '$1').replace(/<[^>]+>/g, '').replace(/&#?\w+;/g, m => ent[m] !== undefined ? ent[m] : (m.startsWith('&#x') ? String.fromCharCode(parseInt(m.slice(3, -1), 16)) : m.startsWith('&#') ? String.fromCharCode(+m.slice(2, -1)) : m)).replace(/\s+/g, ' ').trim();
const unesc = s => s.replace(/\\(['"`\\])/g, '$1').replace(/\\n/g, ' ');
/* all text:'...' entries in a chunk of JS */
function stepTexts(js) {
  const out = [], re = /\btext:\s*(?:'((?:\\.|[^'\\])*)'|"((?:\\.|[^"\\])*)"|`((?:\\.|[^`\\])*)`)/g; let m;
  while ((m = re.exec(js))) out.push(txt(unesc(m[1] ?? m[2] ?? m[3])));
  return out;
}
/* The Lab.steps(...) call (or gelGuidance call) text for a container id */
function callFor(js, id) {
  const i = js.indexOf("Lab.steps('#" + id + "'"); if (i < 0) return null;
  const j = js.indexOf('], {', i), k = js.indexOf('\n  Lab.', i + 10);
  const end = j > 0 ? Math.min(...[j, k].filter(x => x > 0)) : k;
  return js.slice(i, end > i ? end : i + 4000);
}
function parse(file) {
  const html = fs.readFileSync(path.join(ROOT, file), 'utf8');
  const get = (re) => { const m = html.match(re); return m ? txt(m[1]) : ''; };
  const eyebrow = get(/<div class="eyebrow">([^<]*)<\/div>/);
  const bigIdea = get(/<nav class="crumbs"[^>]*>.*?<\/a><span>([^<]*)<\/span>/);
  const lab = { id: file.replace('.html', ''), n: +file.match(/\d+/)[0], title: get(/<h1>(.*?)<\/h1>/), dq: get(/<p class="driving-q">(.*?)<\/p>/), eyebrow, bigIdea };
  /* safety callouts (a "Safety" tip on the two computer labs is kept and flagged virtual) */
  const sc = [], sre = /<div class="callout (callout--(?:safety|tip))[^"]*"><div class="callout-title">([^<]*)<\/div>([\s\S]*?)<\/div>\s*(?=<\/|<div|<!--|\n\s*<(?:p|h|section))/g; let m;
  while ((m = sre.exec(html))) {
    if (m[1] !== 'callout--safety' && !/^safety/i.test(m[2].trim())) continue;
    const body = m[3], lis = [...body.matchAll(/<li>([\s\S]*?)<\/li>/g)].map(x => txt(x[1]));
    const items = lis.length ? lis : txt(body.replace(/<\/p>/g, '</p> ')).split(/(?<=[.!?])\s+(?=[A-Z])/).filter(Boolean);
    sc.push({ title: txt(m[2]), virtual: m[1] !== 'callout--safety', items });
  }
  lab.safety = sc;
  const js = [...html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)].map(x => x[1]).join('\n');
  const parts = [], secRe = /<section class="step[^"]*"[^>]*data-step="([^"]+)"([^>]*)>([\s\S]*?)(?=<section class="step|<footer|<\/main>|$)/g;
  const used = new Set();
  while ((m = secRe.exec(html))) {
    const name = txt(m[1]), mins = +((m[2].match(/data-minutes="(\d+)"/) || [])[1] || 0), body = m[3];
    let slug = slugify(name) || 'part-' + (parts.length + 1), base = slug, c = 2; while (used.has(slug)) slug = base + '-' + c++; used.add(slug);
    let steps = [];
    for (const idm of body.matchAll(/id="([\w-]+-steps)"/g)) { const call = callFor(js, idm[1]); if (call) steps.push(...stepTexts(call)); }
    const gel = body.match(/id="(gel\d)"/);
    if (!steps.length && gel) { /* lab 9: gel checklists are built by gelGuidance(P, ...) */
      const P = 'g' + gel[1].slice(3), gi = js.indexOf('function gelGuidance'), ge = js.indexOf('\n}', gi);
      const core = stepTexts(js.slice(gi, ge)), ci = js.indexOf("gelGuidance('" + P + "'"), call = js.slice(ci, Math.min(...['\n}', '\n\n'].map(x => js.indexOf(x, ci)).filter(x => x > 0))), extra = stepTexts(call).filter(t => !/^(Load the samples|Run until|Stain, then)/.test(t));
      const first = /gelGuidance\('\w+', \w+,\s*null/.test(call) ? [] : extra.slice(0, 1);
      steps = [...first, ...core, ...(first.length ? extra.slice(1) : extra)];
    }
    parts.push({ slug, name, minutes: mins, steps });
  }
  lab.parts = parts;
  return lab;
}
const labs = Array.from({ length: 13 }, (_, i) => parse('lab' + String(i + 1).padStart(2, '0') + '.html'));
fs.writeFileSync(path.join(ROOT, 'projector-data.js'),
  '/* Generated by tools/gen-projector-data.js from the lab pages. Do not edit by hand. */\nwindow.PROJECTOR_LABS = ' + JSON.stringify(labs, null, 1) + ';\n');
for (const l of labs) console.log(l.id, l.parts.length + ' parts,', l.parts.reduce((a, p) => a + p.steps.length, 0) + ' steps,', l.safety.length + ' safety');
